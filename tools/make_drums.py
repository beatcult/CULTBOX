"""Turn the drum WAVs in assets/drums/<kit>/ into firmware/src/drums_data.h (16-bit samples in flash).
Each sample is resampled with a proper low-pass to its stored rate (22.05 kHz, or 44.1 kHz for the hats) and may be trimmed
with a fade. Usage: python3 tools/make_drums.py"""
import wave, sys
from pathlib import Path
import numpy as np
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parent.parent
# (pad name on the screen, file, stored rate, trim to seconds or 0, fade seconds)
KITS = {
    "ELKA": [
        ("Kick", "Elka_kick.wav", 22050, 0, 0),
        ("Snr 1", "Elka_snare_1.wav", 22050, 0, 0),
        ("Snr 2", "Elka_snare_2.wav", 22050, 0, 0),
        ("Tom 1", "Elka_tom_1.wav", 22050, 0, 0),
        ("Tom 2", "Elka_tom_2.wav", 22050, 0, 0),
        ("Conga", "Elka_conga.wav", 22050, 0, 0),
        ("Clave", "Elka_claves.wav", 22050, 0, 0),
        ("Cowbl", "Elka_cowbell.wav", 22050, 0, 0),
        ("Hat C", "Elka_hihat_closed.wav", 44100, 0, 0),
        ("Hat O", "Elka_hihat_open.wav", 44100, 0.70, 0.20),
    ],
}

def load(path):
    w = wave.open(str(path))
    assert w.getnchannels() == 1 and w.getsampwidth() == 2, path
    return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64), w.getframerate()

def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Drum samples (16-bit, mono) from assets/drums/. Generated by tools/make_drums.py: do not edit. */"]
    total = 0
    for kit, pads in KITS.items():
        names = []
        for i, (name, f, rate, trim, fade) in enumerate(pads):
            x, sr = load(ROOT / "assets/drums" / kit.lower() / f)
            lead = int(np.argmax(np.abs(x) > np.abs(x).max() * 0.02))     # the silence before the hit is latency: start 0.5 ms before it
            x = x[max(0, lead - int(0.0005 * sr)):]
            if trim:
                x = x[:int(trim * sr)]
                n = int(fade * sr)
                if n: x[-n:] *= 0.5 * (1 + np.cos(np.linspace(0, np.pi, n)))
            if rate != sr:
                from math import gcd
                g = gcd(rate, sr)
                x = resample_poly(x, rate // g, sr // g)
            y = np.clip(np.round(x), -32768, 32767).astype(np.int16)
            total += len(y) * 2
            sym = f"DRUM_{kit}_{i}"
            out.append(f"static const int16_t {sym}[{len(y)}] = {{")
            for j in range(0, len(y), 16):
                out.append("    " + ",".join(str(int(v)) for v in y[j:j + 16]) + ",")
            out.append("};")
            names.append((name, sym, len(y), rate))
            print(f"{kit} {i} {name:8s} {len(y):6d} samples at {rate} Hz = {len(y)*2:6d} B  ({len(y)/rate:.3f} s)")
        out.append(f"#define DRUM_{kit}_PADS {len(names)}")
        out.append(f"static const char *const DRUM_{kit}_NAMES[{len(names)}] = {{" + ", ".join(f'"{n[0]}"' for n in names) + "};")
        out.append(f"static const drum_sample_t DRUM_{kit}[{len(names)}] = {{")
        for name, sym, n, rate in names:
            out.append(f'    {{"{name}", {sym}, {n}, {rate}}},')
        out.append("};")
    (ROOT / "firmware/src/drums_data.h").write_text("\n".join(out) + "\n")
    print("total", total, "B")

main()
